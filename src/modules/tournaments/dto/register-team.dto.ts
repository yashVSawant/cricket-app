import { IsNotEmpty, IsString } from 'class-validator';
import { ApiProperty } from '@nestjs/swagger';

export class RegisterTeamToTournamentDto {
  @ApiProperty({ example: 'TM-A1B2C3', description: 'Unique Team Key generated by Team Captain' })
  @IsString()
  @IsNotEmpty({ message: 'Team Key is required' })
  teamKey: string;
}

